export const AUTO_DETECT_LANGUAGE = { code: 'auto', name: 'Auto' };

export function getLanguageByCode(code) {
  if (!code) return SUPPORTED_LANGUAGES.find(l => l.code === 'en') || SUPPORTED_LANGUAGES[0];
  const normalized = code.toLowerCase().trim();
  if (normalized === 'auto' || normalized === 'autodetect' || normalized === 'auto-detect') {
    return AUTO_DETECT_LANGUAGE;
  }
  return SUPPORTED_LANGUAGES.find(l => l.code.toLowerCase() === normalized || l.name.toLowerCase() === normalized) || SUPPORTED_LANGUAGES.find(l => l.code === 'en') || SUPPORTED_LANGUAGES[0];
}

